"""식품군별 1회 섭취 중량 (SPEC 7.3 개정).

**왜 필요한가**

식약처 영양성분DB는 모든 수치를 100g 기준으로 정규화해서 준다
(``SERVING_SIZE`` 가 항상 "100g"). 그런데 실제로 사람은 찌개를 300g 먹고
김치는 40g 먹는다. 100g 농도만 비교하면 수분이 많은 국물 음식이 구조적으로
과소평가된다.

실측으로 확인된 문제 (100g 기준 나트륨):

===============  ========  ==========================
음식             mg/100g   600mg/100g 기준 판정
===============  ========  ==========================
김치찌개              491   통과 (!)
된장찌개              318   통과 (!)
라면                 283   통과 (!)
배추김치              551   통과
===============  ========  ==========================

즉 기존 기준으로는 **고혈압 사용자가 김치찌개에 "먹어도 돼요"를 받는다.**
서비스의 존재 이유가 무너지는 오류다.

1회 섭취량으로 환산하면 김치찌개 300g = 1,473mg 으로, 하루 나트륨 목표
2,000mg의 74%를 한 그릇에서 채운다. 이것이 사용자가 알아야 할 사실이다.

**출처와 한계**

아래 중량은 한국인 영양소 섭취기준의 '1인 1회 분량'을 참고한 근사값이다.
영양 전문가 검토를 받아야 하며, 그때까지는 설정으로 조정 가능하게 둔다.
"""

from __future__ import annotations

from typing import Final

#: 식품군(FOOD_CAT1_NM) -> 1회 섭취 중량(g)
PORTION_GRAMS: Final[dict[str, float]] = {
    "밥류": 250.0,
    "죽 및 스프류": 300.0,
    "국 및 탕류": 350.0,
    "찌개 및 전골류": 300.0,
    "면 및 만두류": 400.0,
    "구이류": 120.0,
    "볶음류": 100.0,
    "조림류": 80.0,
    "튀김류": 80.0,
    "전·적 및 부침류": 80.0,
    "나물·숙채류": 60.0,
    "생채·무침류": 60.0,
    "김치류": 40.0,
    "젓갈류": 15.0,
    "장아찌·절임류": 20.0,
    "회류": 100.0,
    "수·조·어·육류": 100.0,
    "빵 및 과자류": 80.0,
    "음료 및 차류": 200.0,
    "유제품류 및 빙과류": 200.0,
    "소스류": 20.0,
    "장류": 15.0,
}

#: 식품군을 모를 때. 100g로 두면 기존 동작과 같아 보수적이지 않으므로,
#: 일반적인 한 끼 반찬 수준인 150g을 기본값으로 쓴다.
DEFAULT_PORTION_GRAMS: Final[float] = 150.0


def portion_for(food_category: str | None) -> float:
    """식품군에 해당하는 1회 섭취 중량(g)."""
    if not food_category:
        return DEFAULT_PORTION_GRAMS
    return PORTION_GRAMS.get(food_category.strip(), DEFAULT_PORTION_GRAMS)


def scale_to_portion(value_per_100g: float, food_category: str | None) -> float:
    """100g 기준 수치를 1회 섭취량 기준으로 환산."""
    return value_per_100g * portion_for(food_category) / 100.0
